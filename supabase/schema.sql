-- true se quem está logada é uma das advogadas (security definer: lê "advogadas" sem passar pela RLS dela)
create or replace function public.e_autorizada()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (select 1 from public.advogadas where user_id = auth.uid());
$$;
revoke all on function public.e_autorizada() from public;
grant execute on function public.e_autorizada() to authenticated;

-- Vincula o login à advogada pelo e-mail, quando o e-mail está confirmado (conta criada no painel já vem confirmada)
create or replace function public.vincular_advogada()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.advogadas set user_id = new.id
   where email = lower(new.email) and user_id is distinct from new.id;
  return new;
end;
$$;
revoke all on function public.vincular_advogada() from public;
drop trigger if exists vincular_advogada on auth.users;
create trigger vincular_advogada
  after insert or update of email, email_confirmed_at on auth.users
  for each row when (new.email_confirmed_at is not null)
  execute function public.vincular_advogada();

-- E o contrário: cadastrar ou trocar o e-mail de uma advogada (SQL Editor) já liga ao login que existir com ele;
-- apagar o e-mail (email = null) tira o acesso
create or replace function public.vincular_login()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new.email := nullif(lower(trim(new.email)), '');
  new.user_id := (select u.id from auth.users u
                   where lower(u.email) = new.email and u.email_confirmed_at is not null);
  return new;
end;
$$;
revoke all on function public.vincular_login() from public;
drop trigger if exists vincular_login on public.advogadas;
create trigger vincular_login
  before insert or update of email on public.advogadas
  for each row execute function public.vincular_login();

-- RLS em todas as tabelas: só usuária autorizada lê e escreve. (select …) = avaliado uma vez por consulta.
do $$
declare
  t text;
begin
  foreach t in array array[
    'advogadas', 'advogados_cooperacao', 'pessoas', 'processos', 'processo_advogada', 'comunicacoes', 'comunicacao_advogada',
    'comunicacao_analise', 'movimentos', 'tarefas', 'tarefas_geradas', 'clientes_colunas', 'clientes',
    'checklist_itens', 'lancamentos', 'parcelas', 'pagamentos', 'feriados', 'tipos_ato', 'lembretes_feitos', 'meta', 'sync_erros'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists autorizadas on public.%I', t);
    execute format('create policy autorizadas on public.%I for all to authenticated '
                   'using ((select public.e_autorizada())) with check ((select public.e_autorizada()))', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end;
$$;
grant usage on schema public to authenticated;  -- explícito: vale mesmo com a Data API desligada
grant usage, select on all sequences in schema public to authenticated;

-- Quem pode entrar só muda pelo SQL Editor: pelo app, só nome e cor das advogadas são editáveis
revoke insert, update, delete on public.advogadas from authenticated;
grant update (nome, cor) on public.advogadas to authenticated;

-- Liga os logins que já existiam antes destes gatilhos (projeto criado com uma versão anterior deste arquivo)
update public.advogadas a set user_id = u.id
  from auth.users u
 where a.email = lower(u.email) and u.email_confirmed_at is not null and a.user_id is distinct from u.id;
