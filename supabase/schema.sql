-- =====================================================================================================
-- Meus processos — schema do Supabase (Postgres + Auth + RLS)
--
-- Como usar: Supabase → SQL Editor → New query → cole este arquivo inteiro → Run.
-- Pode rodar de novo sem estragar nada (IF NOT EXISTS / OR REPLACE): é assim que se aplica uma versão nova.
--
-- Acesso: só entra quem está na tabela "advogadas" com o login (auth.users) vinculado. Todas as tabelas
-- têm RLS; as duas advogadas veem e editam tudo (o filtro por advogada é da tela, não de permissão).
-- O app (backend em Python) conecta no banco e, a cada requisição, assume o papel "authenticated" com o
-- token da usuária logada — então as mesmas políticas valem para o app e para a API do Supabase.
-- =====================================================================================================

-- ---------------------------------------------------------------------------------------------------
-- Advogadas (quem pode entrar) e equipe (responsáveis nos itens de checklist, sem login)
-- ---------------------------------------------------------------------------------------------------
create table if not exists public.advogadas (
  id          bigint generated by default as identity primary key,
  nome        text not null,
  oab_numero  text not null,
  oab_uf      text not null,
  cor         text not null default '#7c3aed' check (cor ~ '^#[0-9a-fA-F]{6}$'),
  email       text unique check (email = lower(email)),       -- e-mail do login dela
  user_id     uuid unique references auth.users (id) on delete set null,  -- preenchido sozinho (trigger abaixo)
  criado_em   timestamptz not null default now(),
  unique (oab_numero, oab_uf)
);
comment on table public.advogadas is 'Advogadas do escritório. Só quem tem user_id vinculado acessa o app.';

create table if not exists public.advogados_cooperacao (      -- de fora do escritório: processo com eles = "em cooperação"
  id          bigint generated by default as identity primary key,
  nome        text not null default '',
  oab_numero  text not null default '',
  oab_uf      text not null default '',
  criado_em   timestamptz not null default now(),
  check (nome <> '' or oab_numero <> '')
);

create table if not exists public.pessoas (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  ativo      boolean not null default true,                   -- false = tirada da lista (itens antigos mantêm o nome)
  criado_em  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------------------------------
-- Processos e o que vem dos tribunais (DJEN = publicações; DataJud = movimentos)
-- ---------------------------------------------------------------------------------------------------
create table if not exists public.processos (
  numero            text primary key check (numero ~ '^[0-9]{20}$'),
  tribunal          text,
  alias             text,                                      -- índice do DataJud (ex.: tjpr)
  origem            text,                                      -- djen | manual
  orgao             text,
  classe            text,
  assuntos          jsonb,                                     -- ["nome", ...]
  grau              text,
  data_ajuizamento  date,
  sistema           text,
  instancias        jsonb,                                     -- resumo por grau devolvido pelo DataJud
  partes            jsonb,                                     -- {"ativo": [...], "passivo": [...], "outros": [...]}
  datajud_status    text check (datajud_status in ('ok', 'sem_dados', 'erro', 'sem_alias')),
  datajud_msg       text,
  datajud_em        timestamptz,
  ult_mov_data      timestamp,                                 -- hora local do tribunal
  ult_mov_texto     text,
  ult_pub_data      date,
  ult_pub_texto     text,
  ult_atividade     timestamp,
  novidade_em       timestamptz,                               -- algo novo capturado
  visto_em          timestamptz,                               -- marcado como visto
  contagem          text check (contagem in ('uteis', 'corridos')),  -- contagem de prazo deste processo (null = padrão)
  busca             text,                                      -- texto normalizado (sem acento, minúsculo) para busca
  criado_em         timestamptz not null default now(),
  cooperacao        boolean not null default false,            -- consta advogado de cooperação (refeito a cada atualização)
  cooperacao_manual boolean                                    -- marcação à mão, vale por cima da automática; null = automática
);

create table if not exists public.processo_advogada (          -- N:N: um processo pode ser das duas
  numero       text not null references public.processos (numero) on delete cascade,
  advogada_id  bigint not null references public.advogadas (id) on delete cascade,
  origem       text,                                           -- djen | manual | migracao
  criado_em    timestamptz not null default now(),
  primary key (numero, advogada_id)
);
create index if not exists ix_pa_advogada on public.processo_advogada (advogada_id);

create table if not exists public.comunicacoes (               -- publicações do DJEN
  hash            text primary key,
  djen_id         bigint,
  numero          text not null references public.processos (numero) on delete cascade deferrable initially deferred,
  tribunal        text,
  orgao           text,
  tipo            text,
  tipo_documento  text,
  classe          text,
  data_disp       date,
  texto           text,
  texto_original  text,
  link            text,
  destinatarios   jsonb,
  advogados       jsonb,
  busca           text,
  capturado_em    timestamptz not null default now()
);
create index if not exists ix_com_numero on public.comunicacoes (numero, data_disp);

create table if not exists public.comunicacao_advogada (       -- qual busca por OAB trouxe cada publicação
  hash         text not null references public.comunicacoes (hash) on delete cascade,
  advogada_id  bigint not null references public.advogadas (id) on delete cascade,
  primary key (hash, advogada_id)
);

create table if not exists public.comunicacao_analise (        -- publicações já varridas por "Verificar prazos"
  hash          text primary key references public.comunicacoes (hash) on delete cascade,
  analisado_em  timestamptz,
  resultado     text,                                          -- prazo | sem_prazo | ja_vencido | erro
  detalhe       text
);

create table if not exists public.movimentos (                 -- movimentos do DataJud
  chave         text primary key,
  numero        text not null references public.processos (numero) on delete cascade,
  grau          text,
  codigo        integer,
  data_hora     timestamp,
  nome          text,
  complementos  text,
  orgao         text,
  capturado_em  timestamptz not null default now()
);
create index if not exists ix_mov_numero on public.movimentos (numero, data_hora);

-- ---------------------------------------------------------------------------------------------------
-- Monitoramento: prazos, tarefas e audiências (cards do Kanban)
-- ---------------------------------------------------------------------------------------------------
create table if not exists public.tarefas (
  id                bigint generated by default as identity primary key,
  titulo            text not null,
  tipo              text not null default 'tarefa' check (tipo in ('prazo', 'tarefa', 'audiencia')),
  status            text not null default 'a_fazer'
                    check (status in ('sugerido', 'a_fazer', 'andamento', 'aguardando', 'concluido', 'descartado')),
  status_anterior   text,                                      -- coluna de onde saiu ao concluir (para restaurar)
  numero            text,                                      -- processo (pode não estar na lista: sem FK)
  advogada_id       bigint references public.advogadas (id) on delete set null,  -- null = as duas / a definir
  prazo_fatal       date,
  data_interna      date,
  hora              time,
  prioridade        text not null default 'media' check (prioridade in ('alta', 'media', 'baixa')),
  observacoes       text,
  origem            text not null default 'manual' check (origem in ('manual', 'djen', 'sigilo')),
  comunicacao_hash  text,                                      -- publicação que gerou a sugestão
  trecho            text,
  calculo           jsonb,                                     -- memória de cálculo do prazo
  conferir          boolean not null default false,
  aviso             text,
  criado_em         timestamptz not null default now(),
  atualizado_em     timestamptz,
  concluido_em      timestamptz
);
create index if not exists ix_tarefas_status on public.tarefas (status, prazo_fatal);
create index if not exists ix_tarefas_numero on public.tarefas (numero);

create table if not exists public.tarefas_geradas (            -- tarefas automáticas já criadas (não recria)
  chave      text primary key,                                 -- ex.: sigilo:<numero>:<segunda-feira>
  criado_em  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------------------------------
-- Clientes (quadro Kanban) e checklists (de clientes e de tarefas)
-- ---------------------------------------------------------------------------------------------------
create table if not exists public.clientes_colunas (
  id       integer primary key,
  posicao  integer not null,
  nome     text not null default ''
);
insert into public.clientes_colunas (id, posicao, nome)
select i, i, '' from generate_series(1, 5) as i
on conflict (id) do nothing;

create table if not exists public.clientes (
  id               bigint generated by default as identity primary key,
  coluna_id        integer not null references public.clientes_colunas (id),
  posicao          integer not null default 0,
  nome             text not null,
  tipo             text not null default 'processo' check (tipo in ('processo', 'inicial', 'preventivo')),
  numero           text,                                       -- processo (só no tipo "processo")
  prazo_descricao  text,                                       -- prazo fatal interno (sem processo)
  prazo_data       date,
  prazo_hora       time,
  aniversario      date,                                       -- gera "Parabenizar" todo ano na Agenda
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz
);
create index if not exists ix_clientes_coluna on public.clientes (coluna_id, posicao);

create table if not exists public.checklist_itens (
  id           bigint generated by default as identity primary key,
  tarefa_id    bigint references public.tarefas (id) on delete cascade,
  cliente_id   bigint references public.clientes (id) on delete cascade,
  item_id      text not null,                                  -- id estável usado pela tela
  posicao      integer not null,
  texto        text not null,
  feito        boolean not null default false,
  data         date,
  hora         time,
  advogada_id  bigint references public.advogadas (id) on delete set null,  -- responsável (advogada) …
  pessoa_id    bigint references public.pessoas (id) on delete set null,    -- … ou pessoa da equipe
  check (num_nonnulls(tarefa_id, cliente_id) = 1),             -- o item é de uma tarefa OU de um cliente
  check (hora is null or data is not null),
  check (advogada_id is null or pessoa_id is null)
);
create unique index if not exists ux_itens_tarefa on public.checklist_itens (tarefa_id, item_id) where tarefa_id is not null;
create unique index if not exists ux_itens_cliente on public.checklist_itens (cliente_id, item_id) where cliente_id is not null;
create index if not exists ix_itens_data on public.checklist_itens (data) where data is not null;

-- ---------------------------------------------------------------------------------------------------
-- Financeiro: lançamentos (honorários) e parcelas (a entrada é a parcela 0). Valores em centavos.
-- ---------------------------------------------------------------------------------------------------
create table if not exists public.lancamentos (
  id             bigint generated by default as identity primary key,
  cliente        text not null,                                -- nome por extenso
  cliente_id     bigint references public.clientes (id) on delete set null,  -- card de Clientes com o mesmo nome
  numero         text,                                         -- processo vinculado (opcional)
  valor_total    bigint not null check (valor_total > 0),
  entrada        bigint not null default 0 check (entrada >= 0),
  entrada_data   date,
  valor_parcela  bigint not null default 0 check (valor_parcela >= 0),
  qtd_parcelas   integer not null default 0 check (qtd_parcelas between 0 and 360),
  observacoes    text,
  inadimplente   boolean not null default false,               -- fora da renda do mês (continua no total a receber)
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz
);

create table if not exists public.parcelas (
  id             bigint generated by default as identity primary key,
  lancamento_id  bigint not null references public.lancamentos (id) on delete cascade,
  numero         integer not null check (numero >= 0),         -- 0 = entrada
  vencimento     date not null,                                -- lembrete na Agenda cai no dia seguinte
  valor          bigint not null check (valor >= 0),
  pago           boolean not null default false,               -- resumo dos pagamentos: true = quitada (pago >= valor)
  pago_em        date,                                         -- data do pagamento que quitou
  unique (lancamento_id, numero),
  check ((pago and pago_em is not null) or (not pago and pago_em is null))
);
create index if not exists ix_parcelas_venc on public.parcelas (vencimento);

create table if not exists public.pagamentos (                 -- histórico de pagamentos (parciais ou não) de cada parcela
  id          bigint generated by default as identity primary key,
  parcela_id  bigint not null references public.parcelas (id) on delete cascade,
  valor       bigint not null check (valor > 0),               -- centavos
  data        date not null,
  criado_em   timestamptz not null default now()
);
create index if not exists ix_pagamentos on public.pagamentos (parcela_id);

